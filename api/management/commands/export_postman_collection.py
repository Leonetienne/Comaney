"""Writes api/Comaney_API.postman_collection.json: one request per registered API operation."""
import json
import re
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand

from api.operations import CONCERNS, REGISTRY

OUTPUT = Path(settings.BASE_DIR) / "api" / "Comaney_API.postman_collection.json"
_PATH_PARAM = re.compile(r"<int:(\w+)>")
_EMPTY = {"string": "", "integer": 0, "number": 0, "boolean": True, "array": [], "object": {}}
_SAMPLES = {
    "expenses_create": {"title": "Coffee", "type": "expense", "value": "4.20", "payee": "Cafe", "settled": True},
    "expenses_update": {"value": "3.90"},
    "expenses_bulk": {"action": "settle", "ids": [1, 2]},
    "scheduled_create": {
        "title": "Rent", "type": "expense", "value": "900",
        "repeat_every_factor": 1, "repeat_every_unit": "months", "repeat_base_date": "2025-01-01",
    },
    "projects_create": {"name": "Ibiza", "description": "Summer trip"},
    "settlements_create": {"creditor": {"type": "feuser", "id": 1}, "amount": "20.00"},
    "approvals_decide": {"kind": "consent", "expense_id": 1, "approve": True},
    "account_update": {"email_notifications": False},
}
DESCRIPTION = (
    "Comaney REST API v2. Set the `base_url` and `api_key` collection variables before use.\n\n"
    "**Authentication**: every request needs `Authorization: Bearer <api_key>`; generate the key in Settings.\n\n"
    "**Dates**: ISO 8601 (`YYYY-MM-DD`). **Types**: `expense`, `income`, `savings_dep`, `savings_wit`.\n\n"
    "**Periods**: `date_from`/`date_to` together, or `year`/`month`/`view`; anything left out falls back "
    "to the current financial month.\n\n"
    "Generated by `manage.py export_postman_collection` from the API registry (api/registry.py)."
)


def _example_body(op) -> dict:
    """A hand-written sample, else every required body argument with an empty value of its type."""
    if op.name in _SAMPLES:
        return _SAMPLES[op.name]
    path_params = set(_PATH_PARAM.findall(op.path))
    body = {}
    for key in op.required:
        if key in path_params:
            continue
        schema = op.params[key]
        kind = schema.get("type")
        kind = kind[0] if isinstance(kind, list) else kind
        body[key] = schema["enum"][0] if "enum" in schema else _EMPTY.get(kind, "")
    return body


def _request(op, variables) -> dict:
    path_params = _PATH_PARAM.findall(op.path)
    for name in path_params:
        variables.setdefault(name, "")
    path = _PATH_PARAM.sub(r"{{\1}}", op.path)
    url = {
        "raw": "{{base_url}}/api/v2/" + path,
        "host": ["{{base_url}}"],
        "path": ["api", "v2", *[s for s in path.split("/") if s], ""],
    }
    request = {"method": op.method, "header": [], "url": url, "description": op.description}
    if op.method in ("GET", "DELETE"):
        query = [
            {"key": k, "value": "", "disabled": k not in op.required}
            for k in op.params if k not in path_params
        ]
        if query:
            url["query"] = query
            enabled = "&".join(f"{q['key']}=" for q in query if not q["disabled"])
            if enabled:
                url["raw"] += "?" + enabled
    else:
        request["header"] = [{"key": "Content-Type", "value": "application/json"}]
        request["body"] = {
            "mode": "raw", "raw": json.dumps(_example_body(op), indent=2), "options": {"raw": {"language": "json"}},
        }
    return {"name": op.name.replace("_", " ").capitalize(), "request": request}


def build_collection() -> dict:
    variables = {"base_url": "https://your-comaney-instance.example.com", "api_key": "your-api-key-here"}
    folders = [
        {"name": label, "item": [_request(op, variables) for op in REGISTRY.values() if op.concern == concern]}
        for concern, label in CONCERNS.items()
    ]
    return {
        "info": {
            "name": "Comaney API",
            "description": DESCRIPTION,
            "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
        },
        "variable": [{"key": k, "value": v, "type": "string"} for k, v in variables.items()],
        "auth": {"type": "bearer", "bearer": [{"key": "token", "value": "{{api_key}}", "type": "string"}]},
        "item": folders,
    }


class Command(BaseCommand):
    help = "Regenerate the Postman collection from the API registry."

    def handle(self, *args, **options):
        OUTPUT.write_text(json.dumps(build_collection(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        self.stdout.write(f"Wrote {OUTPUT}")
